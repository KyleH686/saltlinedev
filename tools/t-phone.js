const {chromium,devices}=require('playwright');
(async()=>{const b=await chromium.launch({args:['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist']});
const ctx=await b.newContext({...devices['iPhone 13 landscape']});
const p=await ctx.newPage();
const errs=[];p.on('pageerror',e=>errs.push('PAGEERR '+e.message));p.on('console',m=>{if(m.type()==='error')errs.push('ERR: '+m.text().slice(0,300))});
await p.goto('file://'+process.cwd()+'/dist/test-phone.html?q=test&noaudio=1');
await p.waitForFunction(()=>window.__ready,null,{timeout:180000});
await p.waitForTimeout(3000);
await p.evaluate(()=>{__G.render.frame=()=>{};});
await p.tap('[data-diff=recruit]',{force:true});
await p.waitForTimeout(800); await p.tap('[data-act=deploy]',{force:true});
await p.waitForTimeout(3000);
console.log(await p.evaluate(()=>JSON.stringify({st:__G.game.state,scr:__G.game.menus.screen,diff:__G.game.menus.settings.difficulty,touch:__G.input.touch})));
await p.evaluate(()=>{ if(__G.game.state==='title') document.querySelector('[data-act=deploy]').click(); });
await p.waitForFunction(()=>__G.game.state==='playing',null,{timeout:120000});
await p.evaluate(async()=>{const G=__G;const sleep=ms=>new Promise(r=>setTimeout(r,ms));
  G.enemies.clear(); const P=G.player; const h=G.enemies.spawn("hound",new G.THREE.Vector3(P.pos.x+9,0,P.pos.z),{state:"patrol"});
  h.patrolSpeed=0; await sleep(400);});
await p.tap('.t-crouch',{force:true});
await p.waitForTimeout(2500);
const info=await p.evaluate(()=>({touch:__G.input.touch,crouch:__G.player.crouching,meter:document.querySelector('.sl-detect').className,btns:[...document.querySelectorAll('.t-btn')].map(b=>{const r=b.getBoundingClientRect();return [b.dataset.a,Math.round(r.x),Math.round(r.y),Math.round(r.width),getComputedStyle(b).display]})}));
console.log(JSON.stringify(info));
await p.screenshot({path:'phone-play.png',timeout:120000});
console.log(errs.join('\n'));await b.close();})();
